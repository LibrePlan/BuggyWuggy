package org.buggywuggy.issue;

import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import java.time.Instant;
import java.time.LocalDate;
import org.buggywuggy.user.UserAccount;

/**
 * An issue. Multi-valued fields (labels, components, versions) live in their own tables and
 * are handled by {@link IssueFieldStore}; {@code search_vector} is generated by PostgreSQL.
 */
@Entity
@Table(name = "issue")
public class Issue {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    private long projectId;
    private long number;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "issue_type_id")
    private IssueType issueType;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "status_id")
    private Status status;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "priority_id")
    private Priority priority;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "resolution_id")
    private Resolution resolution;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "parent_id")
    private Issue parent;

    private String summary;
    private String description;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "reporter_id")
    private UserAccount reporter;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "assignee_id")
    private UserAccount assignee;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "creator_id")
    private UserAccount creator;

    private LocalDate dueDate;
    private Instant createdAt;
    private Instant updatedAt;
    private Instant resolvedAt;

    @Version
    private long version;

    protected Issue() {
    }

    public Issue(long projectId, long number, IssueType issueType, Status status, String summary,
            UserAccount creator, Instant createdAt) {
        this.projectId = projectId;
        this.number = number;
        this.issueType = issueType;
        this.status = status;
        this.summary = summary;
        this.creator = creator;
        this.createdAt = createdAt;
        this.updatedAt = createdAt;
    }

    public Long getId() { return id; }
    public long getProjectId() { return projectId; }
    public long getNumber() { return number; }

    /** To another project, under a number reserved there. */
    void moveTo(long projectId, long number) {
        this.projectId = projectId;
        this.number = number;
    }
    public IssueType getIssueType() { return issueType; }
    public void setIssueType(IssueType issueType) { this.issueType = issueType; }
    public Status getStatus() { return status; }
    public void setStatus(Status status) { this.status = status; }
    public Priority getPriority() { return priority; }
    public void setPriority(Priority priority) { this.priority = priority; }
    public Resolution getResolution() { return resolution; }
    public void setResolution(Resolution resolution) { this.resolution = resolution; }
    public Issue getParent() { return parent; }
    public void setParent(Issue parent) { this.parent = parent; }
    public String getSummary() { return summary; }
    public void setSummary(String summary) { this.summary = summary; }
    public String getDescription() { return description; }
    public void setDescription(String description) { this.description = description; }
    public UserAccount getReporter() { return reporter; }
    public void setReporter(UserAccount reporter) { this.reporter = reporter; }
    public UserAccount getAssignee() { return assignee; }
    public void setAssignee(UserAccount assignee) { this.assignee = assignee; }
    public UserAccount getCreator() { return creator; }
    public LocalDate getDueDate() { return dueDate; }
    public void setDueDate(LocalDate dueDate) { this.dueDate = dueDate; }
    public Instant getCreatedAt() { return createdAt; }
    public Instant getUpdatedAt() { return updatedAt; }
    public void setUpdatedAt(Instant updatedAt) { this.updatedAt = updatedAt; }
    public Instant getResolvedAt() { return resolvedAt; }
    public void setResolvedAt(Instant resolvedAt) { this.resolvedAt = resolvedAt; }
    public long getVersion() { return version; }
}
